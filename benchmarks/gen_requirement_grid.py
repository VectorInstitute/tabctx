#!/usr/bin/env python3
"""Generate a requirement calibration module from bench_memory_pressure.py
--search output (JSON lines): measured working floors (FloorPoint) and the
resident + floor requirement of each shape (Observation), for
WorkingFloorModel and AdaptiveMemoryEstimator (see memory/requirement.py).

Usage:
  gen_requirement_grid.py benchmarks/baselines/minfree-tabicl-kv-a100.jsonl \
      --prefix A100_40GB_TABICL_KV --source "A100-SXM4-40GB, tabicl 2.2.0, kv" \
      --out src/tabctx/memory/calibration_tabicl_a100_requirement.py
"""

from __future__ import annotations

import argparse
import json
import sys

GiB = 1024**3


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("inputs", nargs="+")
    p.add_argument("--prefix", required=True)
    p.add_argument("--source", required=True)
    p.add_argument("--out", required=True)
    args = p.parse_args()
    rows = []
    for path in args.inputs:
        with open(path) as f:
            rows += [json.loads(line) for line in f if line.strip()]
    ok = sorted(
        (r for r in rows if r.get("status") == "ok" and "min_working_gib" in r),
        key=lambda r: (
            r["n_features"] if "n_features" in r else r["features"],
            r["rows"],
        ),
    )
    floors, needs = [], []
    for r in ok:
        n, d = r["rows"], r["features"]
        resident = int(r["resident_gib"] * GiB)
        # The floor can't exceed what the fit used unconstrained: a search
        # result above that is ballast fragmentation, not need.
        used = int((r["unconstrained_peak_gib"] - r["resident_gib"]) * GiB)
        working = min(int(r["min_working_gib"] * GiB), used)
        need = resident + working
        note = (
            f"resident {r['resident_gib']} GiB, unconstrained peak "
            f"{r['unconstrained_peak_gib']} GiB, fit {r['unconstrained_fit_s']}s "
            f"-> {r['fit_s_at_min']}s at the floor"
        )
        floors.append(
            f"    FloorPoint(n_train={n}, n_features={d}, working_bytes={working}, "
            f"resident_bytes={resident}),  # {note}"
        )
        needs.append(
            f"    Observation(n_train={n}, n_features={d}, real_bytes={need}),"
        )
    body = f'''"""GENERATED by benchmarks/gen_requirement_grid.py -- do not hand-edit.

Measured requirements ({args.source}): for each shape, the least free GPU
memory with which a fit succeeded (resident context + working floor), from
benchmarks/bench_memory_pressure.py --search. See memory/requirement.py.
"""

from __future__ import annotations

from tabctx.memory.adaptive import Observation
from tabctx.memory.requirement import FloorPoint

{args.prefix}_FLOOR_POINTS: tuple[FloorPoint, ...] = (
{chr(10).join(floors)}
)

{args.prefix}_REQUIREMENT_GRID: tuple[Observation, ...] = (
{chr(10).join(needs)}
)
'''
    with open(args.out, "w") as f:
        f.write(body)
    print(f"wrote {len(ok)} shapes to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
